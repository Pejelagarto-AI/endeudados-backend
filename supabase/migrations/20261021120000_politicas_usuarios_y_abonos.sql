-- Politicas de UPDATE en usuarios y captura de la tabla abonos (EN-32, EN-58).
--
-- Situacion antes de esta migracion (verificada contra produccion el 21-oct):
--
--   deudas, gastos, ingresos  ALL {authenticated}  ya se pueden editar y borrar
--                                                  desde EN-54 y EN-56
--   usuarios                  INSERT, SELECT       no se puede corregir el perfil
--   abonos                    INSERT, SELECT, DELETE
--                             creada desde el dashboard: no existe en ninguna
--                             migracion, asi que un `db reset` la pierde
--
-- De EN-32 lo unico que faltaba era `usuarios`. Lo de ingresos y gastos ya lo
-- resolvieron las politicas de tipo ALL.
--
-- Por que usuarios tiene UPDATE pero no DELETE: borrar la fila de `usuarios`
-- arrastra ingresos, gastos, deudas y abonos (todas con ON DELETE CASCADE),
-- pero deja vivo el usuario en `auth.users`. Quedaria una cuenta que inicia
-- sesion y no tiene perfil. Eliminar la cuenta se hace completo en EN-44, con
-- una funcion que borra desde `auth.users` hacia abajo.

-- ---------------------------------------------------------------------------
-- 1. usuarios: el titular corrige su perfil (Ley 1581, art. 8: rectificar)
-- ---------------------------------------------------------------------------

drop policy if exists usuarios_actualiza_propio on public.usuarios;
create policy usuarios_actualiza_propio on public.usuarios
  for update to authenticated
  using      (auth_id = (select auth.uid()))
  with check (auth_id = (select auth.uid()));

-- La politica dice QUE fila puede tocar; los permisos de columna dicen QUE
-- campos. Sin esto el usuario podria cambiarse el `auth_id` (el with check lo
-- frena, pero mejor no depender de eso) o el `email`, que vive en auth.users y
-- quedaria desincronizado. El correo se cambia por Supabase Auth, no aca.
revoke update on public.usuarios from authenticated, anon;
grant  update (nombre, cedula) on public.usuarios to authenticated;

-- ---------------------------------------------------------------------------
-- 2. abonos: se captura tal como esta en produccion (EN-48)
-- ---------------------------------------------------------------------------

create table if not exists public.abonos (
  id          bigint      generated by default as identity primary key,
  deuda_id    bigint      not null,
  usuario_id  uuid        not null,
  monto       numeric     not null,
  fecha       date        not null default current_date,
  creado_en   timestamptz not null default now(),
  constraint abonos_deuda_fk   foreign key (deuda_id)   references public.deudas (id)   on delete cascade,
  constraint abonos_usuario_fk foreign key (usuario_id) references public.usuarios (id) on delete cascade,
  constraint abonos_monto_mayor_cero check (monto > 0)
);

alter table public.abonos enable row level security;

drop policy if exists "Usuarios pueden ver sus propios abonos" on public.abonos;
create policy "Usuarios pueden ver sus propios abonos" on public.abonos
  for select to authenticated
  using (usuario_id = (select id from public.usuarios where auth_id = auth.uid()));

-- El abono tiene que ser del usuario Y de una deuda del mismo usuario. Sin la
-- segunda condicion alguien podria abonarle a la deuda de otro.
drop policy if exists "Usuarios pueden registrar sus propios abonos" on public.abonos;
create policy "Usuarios pueden registrar sus propios abonos" on public.abonos
  for insert to authenticated
  with check (
    usuario_id = (select id from public.usuarios where auth_id = auth.uid())
    and exists (
      select 1 from public.deudas
      where deudas.id = abonos.deuda_id and deudas.usuario_id = abonos.usuario_id
    )
  );

drop policy if exists "Usuarios pueden eliminar sus propios abonos" on public.abonos;
create policy "Usuarios pueden eliminar sus propios abonos" on public.abonos
  for delete to authenticated
  using (usuario_id = (select id from public.usuarios where auth_id = auth.uid()));

-- Indices en las llaves foraneas, por la misma razon que EN-55: las politicas
-- filtran por usuario_id y el cascade al borrar una cuenta o una deuda recorre
-- la tabla.
create index if not exists abonos_usuario_id_idx on public.abonos (usuario_id);
create index if not exists abonos_deuda_id_idx   on public.abonos (deuda_id);
